function rankKey(role?: string): string {
  return (role || '').trim().toLowerCase().replace(/[ -]+/g, '_');
}

export function rankSymbol(role?: string): string | null {
  const key = rankKey(role);
  return Object.hasOwn(RANK_SYMBOLS, key) ? RANK_SYMBOLS[key as keyof typeof RANK_SYMBOLS] : null;
}

export function rankLabel(role?: string): string {
  const value = (role || '').trim();
  if (!value || rankKey(value) === 'member') return 'Lid';
  const text = value.replace(/_/g, ' ');
  return text.charAt(0).toUpperCase() + text.slice(1);
}
