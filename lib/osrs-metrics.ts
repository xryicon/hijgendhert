function knownMetric(metric?: string): keyof typeof METRICS | null {
  if (typeof metric !== 'string' || !metric || metric.length > 100) return null;
  const key = metric.trim().toLowerCase().replace(/['’]/g, '').replace(/[\s-]+/g, '_');
  const canonical = Object.hasOwn(ALIASES, key) ? ALIASES[key] : key;
  return Object.hasOwn(METRICS, canonical) ? canonical as keyof typeof METRICS : null;
}

export function metricImage(metric?: string): string | null {
  const key = knownMetric(metric);
  return key ? METRICS[key].image : null;
}

export function metricLabel(metric: string): string {
  if (typeof metric !== 'string') return 'Onbekend';
  const key = knownMetric(metric);
  if (key) return METRICS[key].label;
  return metric.trim().replace(/[_-]+/g, ' ').replace(/\b\w/g, character => character.toUpperCase()) || 'Onbekend';
}

